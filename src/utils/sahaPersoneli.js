/**
 * Ham telefon stringini 10 haneli Türk GSM numarasına normalize eder.
 * Tüm rakam olmayan karakterleri çıkarır, baştaki 0'ı atar.
 * Örnek: "(0530) 219-3387" → "5302193387"
 */
export function normalizePhone(raw) {
  const digits = String(raw).replace(/\D/g, '');
  return digits.startsWith('0') ? digits.slice(1) : digits;
}
